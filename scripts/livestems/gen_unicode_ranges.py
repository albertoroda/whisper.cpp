"""Generate the code point range tables used by the patched whisper.cpp BPE pre-tokenizer.

The GPT-2 / Whisper pre-tokenization pattern (tiktoken "multilingual" / "gpt2")
    's|'t|'re|'ve|'m|'ll|'d| ?\\p{L}+| ?\\p{N}+| ?[^\\s\\p{L}\\p{N}]+|\\s+(?!\\S)|\\s+
needs three Unicode classes: \\p{L} (general category L*), \\p{N} (N*) and \\s (White_Space property).
Ranges come from Python's unicodedata; White_Space is the fixed list from PropList.txt.

usage: gen_unicode_ranges.py <out header>
"""
import sys
import unicodedata

WHITE_SPACE = [  # PropList.txt White_Space (stable for many Unicode versions)
    (0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0), (0x1680, 0x1680),
    (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000),
]


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    body = ",\n".join("    {0x%06X, 0x%06X}" % r for r in rs)
    return f"static const livestems_cp_range {name}[] = {{\n{body}\n}};\n" \
           f"static const size_t {name}_count = {len(rs)};\n"


def main(out):
    letters = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    numbers = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("N"))
    header = (
        "// Generated by scripts/livestems/gen_unicode_ranges.py from Python unicodedata "
        f"(Unicode {unicodedata.unidata_version}). Do not edit.\n"
        "#pragma once\n#include <cstddef>\n#include <cstdint>\n\n"
        "struct livestems_cp_range { uint32_t first, last; };\n\n"
        + emit("livestems_cp_letter", letters) + "\n"
        + emit("livestems_cp_number", numbers) + "\n"
        + emit("livestems_cp_space", WHITE_SPACE)
    )
    with open(out, "w") as f:
        f.write(header)
    print(f"letters {len(letters)} ranges, numbers {len(numbers)} ranges, unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    main(sys.argv[1])
